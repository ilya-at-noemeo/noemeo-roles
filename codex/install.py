#!/usr/bin/env python3
"""Install or update the Codex adapter files in Noemeo checkouts.

Run: python3 codex/install.py [--check] /path/to/repo [...]

Writes AGENTS.md, .codex/{config.toml,hooks.json,agents/*.toml} and one
link per skill in .agents/skills/ (this checkout's skills plus the
repo's own, from .claude/skills/). Records what it wrote, with hashes,
in .codex/noemeo-install.json and lists every written path in Git's
info/exclude: the files hold this machine's absolute paths, so they are
never committed. A rerun replaces its own files while they are
unchanged since it wrote them; any other existing file is a conflict,
and a conflict anywhere aborts all writes.

--check writes nothing. It exits 1 when a generated file is missing,
stale or edited, or when an installed copy (Claude's copy of the
plugin, a plugin cache's copy of a linked skill) differs from its source.
"""

import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys

MANIFEST = Path(".codex") / "noemeo-install.json"
BEGIN = "# noemeo codex install (codex/install.py), generated paths of"
END = "# end noemeo codex install"
# The first version wrote one unlabelled block per exclude file.
OLD_BEGIN = "# noemeo codex install: generated paths (codex/install.py)"
PLUGIN_DIRS = (".claude-plugin", "agents", "hooks", "roles", "skills")
SKIP = {"__pycache__", ".DS_Store", ".pytest_cache"}


def skill_dirs(root, repo):
    """Name -> skill directory; a name with two different sources is a conflict."""
    found, conflicts = {}, []
    sources = [*sorted((root / "skills").glob("*/SKILL.md")),
               *sorted((repo / ".claude" / "skills").glob("*/SKILL.md"))]
    for skill in sources:
        name, source = skill.parent.name, skill.parent.resolve()
        if found.get(name, source) != source:
            conflicts.append(f"{repo}: skill {name!r} comes from both {found[name]} and {source}")
        found.setdefault(name, source)
    return found, conflicts


def plan(root, repo):
    """Relative path -> file text (str) or link target (Path)."""
    bridge = root / "codex" / "AGENTS.md"
    changes = {
        Path("AGENTS.md"): (
            "# Noemeo instructions for Codex\n\n"
            "Generated by noemeo-roles `codex/install.py`; rerun it rather than\n"
            "editing this file. Before any task, read and follow:\n\n"
            f"- `{root / 'roles' / 'working-agreement.md'}`\n"
            f"- `{bridge}`\n\n"
            "This repository's `CLAUDE.md`, and any nested `CLAUDE.md` governing\n"
            "the files you change, hold its rules for every tool.\n"
        ),
        Path(".codex") / "config.toml": "[features]\nhooks = true\n",
    }
    skills, conflicts = skill_dirs(root, repo)
    for name, source in skills.items():
        changes[Path(".agents") / "skills" / name] = source
    for source in sorted((root / "agents").glob("*.md")):
        header = source.read_text().split("---", 2)[1]
        metadata = dict(line.split(": ", 1) for line in header.splitlines() if ": " in line)
        name = metadata["name"]
        instructions = (
            f"First read and follow {bridge}. Then read {source} and its role, "
            "skills and references. Those files are the source of truth. "
            "Use Codex tool equivalents; inherit the parent model and permissions. "
            "Respect all read-only, test-only, budget and publication restrictions. "
            "Resolve plugin-root paths against " + str(root) + ". "
            "Do not depend on a Claude Skill tool: open the named SKILL.md directly. "
            "Return the report in the source definition's format."
        )
        # JSON strings are valid TOML basic strings for this plain text.
        changes[Path(".codex") / "agents" / f"{name}.toml"] = (
            f"name = {json.dumps(name)}\n"
            f"description = {json.dumps(metadata['description'])}\n"
            f"developer_instructions = {json.dumps(instructions)}\n"
        )
    command = f"python3 {shlex.quote(str(root / 'codex' / 'hook_adapter.py'))}"
    hooks = {}
    for event, timeout in (("SessionStart", 15), ("PreToolUse", 30),
                           ("PostToolUse", 60), ("Stop", 300), ("SubagentStop", 30)):
        group = {"hooks": [{"type": "command", "command": command, "timeout": timeout}]}
        if event == "SubagentStop":
            group["matcher"] = "(^|:)noemeo-code-reviewer$"
        hooks[event] = [group]
    changes[Path(".codex") / "hooks.json"] = json.dumps({"hooks": hooks}, indent=2) + "\n"
    return changes, conflicts


def digest(content):
    if isinstance(content, Path):
        return f"link:{content}"
    return "sha256:" + hashlib.sha256(content.encode()).hexdigest()


def on_disk(path):
    """The digest of what's at path now, or None if nothing is."""
    if path.is_symlink():
        return f"link:{Path(path.readlink())}"
    if path.is_file():
        return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()
    return "other" if path.exists() else None


def blocked(repo, rel):
    """The outermost parent of rel that is a symlink or a file, if any."""
    hits = [repo / p for p in rel.parents if (repo / p).is_symlink() or (repo / p).is_file()]
    return hits[-1] if hits else None


def read_manifest(repo, conflicts):
    """Relative path -> recorded digest. Anything odd is a conflict, never trusted."""
    path = repo / MANIFEST
    if blocked(repo, MANIFEST) or path.is_symlink() or (path.exists() and not path.is_file()):
        conflicts.append(f"{path}: not a manifest this installer wrote")
        return {}
    try:
        data = json.loads(path.read_text())
    except FileNotFoundError:
        return {}
    except (OSError, ValueError):
        data = None
    if not isinstance(data, dict) or not all(isinstance(v, str) for v in data.values()):
        conflicts.append(f"{path}: not a manifest this installer wrote")
        return {}
    owned = {}
    for key, recorded in data.items():
        rel = Path(key)
        if not key or rel.is_absolute() or ".." in rel.parts:
            conflicts.append(f"{path}: entry {key!r} points outside the checkout")
        else:
            owned[rel] = recorded
    return owned


def exclude_file(repo):
    result = subprocess.run(["git", "-C", str(repo), "rev-parse", "--git-path", "info/exclude"],
                            capture_output=True, text=True)
    if result.returncode:
        return None  # not a Git checkout: nothing to exclude from
    return (repo / result.stdout.strip()).resolve()


def writable(path):
    """Whether path can be written, or created under its nearest existing parent."""
    while not path.exists():
        path = path.parent
    return os.access(path, os.W_OK)


def new_exclude(repo, paths, conflicts):
    """(exclude file, its new text, whether this checkout's block changes).

    Linked worktrees share one exclude file, so each checkout owns only
    the block headed with its own path. Read the file again just before
    writing: another checkout in the same run may have written it.
    """
    target = exclude_file(repo)
    if target is None:
        return None
    if not writable(target):
        conflicts.append(f"{target}: not writable")
        return None
    begin = f"{BEGIN} {repo}"
    kept, current, inside = [], [], False
    lines = target.read_text().splitlines() if target.exists() else []
    for line in lines:
        if line in (begin, OLD_BEGIN):
            inside = True
        elif inside and line == END:
            inside = False
        elif inside:
            current.append(line)
        else:
            kept.append(line)
    if inside:
        conflicts.append(f"{target}: block {begin!r} has no {END!r} line; fix it by hand")
        return None
    block = sorted(f"/{p.as_posix()}" for p in paths)
    changed = OLD_BEGIN in lines or current != block or begin not in lines
    return target, "\n".join([*kept, begin, *block, END]) + "\n", changed


def tracked(repo, rel):
    """Whether Git tracks rel in repo (never, outside a Git checkout)."""
    return subprocess.run(["git", "-C", str(repo), "ls-files", "--error-unmatch", "--", str(rel)],
                          capture_output=True).returncode == 0


def compare(root, repo):
    """(changes, writes, removals, conflicts, stale, manifest, exclude) for repo."""
    changes, conflicts = plan(root, repo)
    owned = read_manifest(repo, conflicts)
    if tracked(repo, MANIFEST):
        conflicts.append(f"{repo / MANIFEST}: tracked by Git, so not this installer's record")
        owned = {}
    writes, removals, stale = {}, [], []
    for rel, content in changes.items():
        path = repo / rel
        if blocked(repo, rel):
            conflicts.append(f"{blocked(repo, rel)}: in the way of generated files beneath it")
            continue
        now = on_disk(path)
        if now == digest(content):
            continue
        if now is None or now == owned.get(rel):
            writes[rel] = content
            stale.append(f"{path}: {'missing' if now is None else 'stale'}")
        else:
            conflicts.append(f"{path}: not written by this installer, or edited since")
    for rel, recorded in owned.items():
        if rel in changes:
            continue
        if blocked(repo, rel):
            conflicts.append(f"{blocked(repo, rel)}: in the way of {rel}, no longer generated")
            continue
        now = on_disk(repo / rel)
        if now is not None and tracked(repo, rel):
            conflicts.append(f"{repo / rel}: tracked by Git; never removed by this installer")
        elif now == recorded:
            removals.append(rel)
            stale.append(f"{repo / rel}: no longer generated")
        elif now is not None:
            conflicts.append(f"{repo / rel}: no longer generated, but edited since")
    # Own only what this installer wrote: a matching file someone else
    # put there stays theirs, out of the manifest and the exclude list.
    manifest = {rel: digest(content) for rel, content in sorted(changes.items())
                if rel in writes or rel in owned}
    if not writable(repo):
        conflicts.append(f"{repo}: not writable")
    exclude = new_exclude(repo, [*manifest, MANIFEST], conflicts)
    if exclude and exclude[2] and manifest:
        stale.append(f"{exclude[0]}: block for {repo} out of date")
    return changes, writes, removals, conflicts, stale, manifest, exclude


def apply(repo, writes, removals, manifest, exclude):
    for rel in removals:
        (repo / rel).unlink()
    for rel, content in writes.items():
        path = repo / rel
        if path.is_symlink() or path.exists():
            path.unlink()
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, Path):
            path.symlink_to(content, target_is_directory=True)
        else:
            path.write_text(content)
    (repo / MANIFEST).parent.mkdir(parents=True, exist_ok=True)
    (repo / MANIFEST).write_text(json.dumps({str(k): v for k, v in manifest.items()}, indent=2) + "\n")
    exclude = exclude and new_exclude(repo, [*manifest, MANIFEST], [])
    if exclude:
        exclude[0].parent.mkdir(parents=True, exist_ok=True)
        exclude[0].write_text(exclude[1])


def tree(directory, parts=None):
    """Relative file path -> sha256 under directory (or only under parts of it)."""
    files = {}
    for top in parts or ("",):
        for path in sorted((directory / top).rglob("*")):
            if path.is_file() and not SKIP & set(path.relative_to(directory).parts):
                files[path.relative_to(directory).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return files


def differs(source, copy, parts=None):
    a, b = tree(source, parts), tree(copy, parts)
    return sorted(name for name in a.keys() | b.keys() if a.get(name) != b.get(name))


def plugin_name(skill):
    """The plugin a skill directory belongs to (<plugin>/skills/<name>)."""
    plugin = skill.parent.parent
    try:
        return json.loads((plugin / ".claude-plugin" / "plugin.json").read_text())["name"]
    except (OSError, ValueError, KeyError, TypeError):
        return plugin.name


def copy_drift(root, repos, home):
    """Installed copies that no longer match the source they were copied from."""
    problems = []
    try:
        markets = json.loads((home / ".claude/plugins/known_marketplaces.json").read_text())
        installed = json.loads((home / ".claude/plugins/installed_plugins.json").read_text())
        ours = {name for name, m in markets.items()
                if Path(m["source"]["path"]).resolve() == root.resolve()
                if m.get("source", {}).get("path")}
        plugins = installed.get("plugins", {})
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        ours, plugins = set(), {}
    for key, entries in plugins.items():
        if key.split("@")[-1] not in ours:
            continue
        for entry in entries:
            copy = Path(entry.get("installPath", "/nonexistent"))
            changed = differs(root, copy, PLUGIN_DIRS) if copy.is_dir() else ["(copy missing)"]
            if changed:
                problems.append(f"Claude's installed {key} ({entry.get('version')}) differs from "
                                f"{root} in {len(changed)} files, e.g. {changed[0]}: "
                                f"run `claude plugin update {key}`")
    # Codex caches plugins as <marketplace>/<plugin>/<version>/skills/<name>;
    # compare only copies of the same plugin's skill.
    caches = sorted((home / ".codex/plugins/cache").glob("*/*/*/skills/*"))
    for repo in repos:
        skills, _ = skill_dirs(root, repo)
        for copy in caches:
            source = skills.get(copy.name)
            if source and copy.parts[-4] == plugin_name(source) and differs(source, copy):
                problems.append(f"Codex's cached skill {copy} differs from its source {source}")
    return sorted(set(problems))


def main(argv, home=None):
    check = "--check" in argv
    root = Path(__file__).resolve().parent.parent
    repos = [Path(arg).resolve() for arg in argv if arg != "--check"]
    if not repos:
        raise SystemExit("Usage: python3 codex/install.py [--check] /path/to/repo [...]")
    for repo in repos:
        if not (repo / ".git").exists() and repo != root.parent:
            raise SystemExit(f"Not a Git checkout: {repo}")
    results = {repo: compare(root, repo) for repo in repos}
    conflicts = [c for r in results.values() for c in r[3]]
    conflicts = list(dict.fromkeys(conflicts))
    if check:
        problems = conflicts + [s for r in results.values() for s in r[4]]
        problems += copy_drift(root, repos, home or Path.home())
        print("\n".join(problems) or "Codex adapter files and installed copies are current.")
        return 1 if problems else 0
    if conflicts:
        raise SystemExit("Existing files need an explicit merge; nothing written:\n" + "\n".join(conflicts))
    # Everything is checked first, but a disk error midway can still leave
    # a run partial; rerunning finishes it.
    count = 0
    for repo, (_, writes, removals, _, _, manifest, exclude) in results.items():
        apply(repo, writes, removals, manifest, exclude)
        count += len(writes) + len(removals)
    print(f"Updated {count} entries across {len(repos)} checkouts. Start a new Codex session "
          "and review/trust its Noemeo hooks before relying on enforcement.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
